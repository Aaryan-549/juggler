// Package wireschema renders Go wire structs as JSDoc typedefs, so the JS that
// reads a message is type-checked against the struct that sends it.
//
// Only tests import it. Each package that owns wire structs lists them in a
// test (wire_typedefs_test.go) and compares the rendering with a checked-in
// web/js/protocol/*.gen.js; UPDATE=1 rewrites the file instead.
//
// The mapping follows what encoding/json puts on the wire:
//   - names come from json tags; `json:"-"` fields and unexported ones are
//     skipped, and an untagged embedded struct's fields are promoted;
//   - omitempty makes a property optional;
//   - a pointer (or []byte) that is not omitempty may be null;
//   - []byte is a base64 string, json.RawMessage and interfaces are unknown,
//     and a type with its own MarshalJSON is unknown too;
//   - a named string or integer type whose package declares literal typed
//     constants of it is the union of those constants;
//   - a named struct is a typedef of its own, described by its doc comment,
//     its properties by their field comments.
//
// Comments and constants are read from the declaring package's source, found
// under the module root, so a type from outside this module renders without
// them.
package wireschema

import (
	"encoding/json"
	"fmt"
	"reflect"
	"slices"
	"strings"
	"time"
)

// banner opens every generated file, as it opens every source file.
const banner = `//     ▄▄ ▄▄ ▄▄  ▄▄▄▄  ▄▄▄▄ ▄▄    ▄▄▄▄▄ ▄▄▄▄
//     ██ ██ ██ ██ ▄▄ ██ ▄▄ ██    ██▄▄  ██▄█▄   Copyright (c) 2026 Julian Storer
//   ▄▄█▀ ▀███▀ ▀███▀ ▀███▀ ██▄▄▄ ██▄▄▄ ██ ██   AGPL-3.0-or-later - see LICENSE
`

// Entry is one top-level typedef: a wire message as one struct sends it.
type Entry struct {
	// Name is the typedef's name. Empty means the struct's own name.
	Name string
	// Value is a value of the struct; only its type is read.
	Value any
	// Types are the values its `type` field is sent with. Empty renders the
	// field from its Go type. One struct sent under several types (a bare
	// frame, a tool command) is several entries.
	Types []string
}

// Config is what a rendering needs besides its entries.
type Config struct {
	// Source names the test that renders the file, for its header.
	Source string
	// Opaque types render as Record<string, unknown>: payloads the wire
	// carries but this contract deliberately does not type.
	Opaque []reflect.Type
	// Rename gives a nested type a typedef name other than its Go name.
	Rename map[reflect.Type]string
}

var (
	marshalerType  = reflect.TypeFor[json.Marshaler]()
	rawMessageType = reflect.TypeFor[json.RawMessage]()
	timeType       = reflect.TypeFor[time.Time]()
)

// renderer is one rendering in progress: the typedefs named so far, and the
// nested structs still to be written.
type renderer struct {
	cfg     Config
	sources *sourceIndex
	names   map[string]reflect.Type // typedef name → the type it declares (nil for an entry)
	nested  map[reflect.Type]string // nested struct → its typedef name
	queue   []reflect.Type          // nested structs not yet written, in first-reached order
}

// Render returns the JS module declaring every entry and each named struct
// they reach.
func Render(cfg Config, entries []Entry) (string, error) {
	r := &renderer{
		cfg:     cfg,
		sources: newSourceIndex(),
		names:   map[string]reflect.Type{},
		nested:  map[reflect.Type]string{},
	}
	var b strings.Builder
	b.WriteString(banner)
	b.WriteString("//\n")
	fmt.Fprintf(&b, "// Code generated by %s; DO NOT EDIT.\n", cfg.Source)
	b.WriteString("// To regenerate: UPDATE=1 make test RUN='TestWireTypedefs'\n")
	b.WriteString("\n/* eslint-disable jsdoc/require-property-description -- a property's description is its Go field's comment, and not every field has one */\n")

	firstEntry := map[reflect.Type]string{} // a struct → the first entry that rendered it
	for _, e := range entries {
		t := reflect.TypeOf(e.Value)
		if t == nil || t.Kind() != reflect.Struct {
			return "", fmt.Errorf("entry %q: %v is not a struct", e.Name, t)
		}
		name := e.Name
		if name == "" {
			name = jsName(t.Name())
		}
		if _, taken := r.names[name]; taken {
			return "", fmt.Errorf("two typedefs are named %s", name)
		}
		r.names[name] = nil
		doc := r.sources.typeDoc(t)
		if first, ok := firstEntry[t]; ok {
			doc = []string{"The same struct as " + first + "."}
		} else {
			firstEntry[t] = name
		}
		block, err := r.typedef(name, t, doc, e.Types)
		if err != nil {
			return "", fmt.Errorf("entry %s: %w", name, err)
		}
		b.WriteString(block)
	}
	for len(r.queue) > 0 {
		t := r.queue[0]
		r.queue = r.queue[1:]
		block, err := r.typedef(r.nested[t], t, r.sources.typeDoc(t), nil)
		if err != nil {
			return "", fmt.Errorf("%s: %w", r.nested[t], err)
		}
		b.WriteString(block)
	}
	b.WriteString("\nexport {};\n")
	return b.String(), nil
}

// typedef renders one struct as a JSDoc typedef, described by doc. types,
// when given, is the literal set its `type` field renders as.
func (r *renderer) typedef(name string, t reflect.Type, doc, types []string) (string, error) {
	fields, err := r.fields(t)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("\n/**\n")
	for _, line := range doc {
		b.WriteString(strings.TrimRight(" * "+line, " ") + "\n")
	}
	fmt.Fprintf(&b, " * @typedef {object} %s\n", name)
	sawType := false
	for _, f := range fields {
		jsType, desc := f.jsType, f.desc
		if f.name == "type" && len(types) > 0 {
			sawType = true
			jsType, desc = literalUnion(types), ""
		}
		prop := f.name
		if f.optional {
			prop = "[" + prop + "]"
		}
		line := fmt.Sprintf(" * @property {%s} %s", jsType, prop)
		if desc != "" {
			line += " - " + desc
		}
		b.WriteString(line + "\n")
	}
	if len(types) > 0 && !sawType {
		return "", fmt.Errorf("%v has no `type` field to carry %v", t, types)
	}
	b.WriteString(" */\n")
	return b.String(), nil
}

// field is one property as it reaches the wire.
type field struct {
	name     string
	jsType   string
	optional bool
	desc     string
}

// fields lists t's properties in encoding/json's order, promoting the fields
// of untagged embedded structs where they sit.
func (r *renderer) fields(t reflect.Type) ([]field, error) {
	var out []field
	for i := range t.NumField() {
		sf := t.Field(i)
		tag := sf.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		ft := sf.Type
		if sf.Anonymous && name == "" {
			et := ft
			if et.Kind() == reflect.Pointer {
				et = et.Elem()
			}
			if et.Kind() == reflect.Struct {
				promoted, err := r.fields(et)
				if err != nil {
					return nil, err
				}
				out = append(out, promoted...)
				continue
			}
		}
		if !sf.IsExported() {
			continue
		}
		if name == "" {
			name = sf.Name
		}
		optional := slices.Contains(strings.Split(opts, ","), "omitempty")
		jsType, err := r.jsType(ft)
		if err != nil {
			return nil, fmt.Errorf("field %s: %w", sf.Name, err)
		}
		if slices.Contains(strings.Split(opts, ","), "string") {
			jsType = "string"
		}
		nullable := ft.Kind() == reflect.Pointer || isBytes(ft)
		if nullable && !optional {
			jsType += "|null"
		}
		desc := r.sources.fieldDoc(t, sf.Name)
		if isBytes(ft) && !strings.Contains(strings.ToLower(desc), "base64") {
			desc = strings.TrimSpace(desc + " Base64.")
		}
		out = append(out, field{name: name, jsType: jsType, optional: optional, desc: desc})
	}
	return out, nil
}

// jsType is the JSDoc type of a value of t, without nullability: a field
// adds |null where its pointer may be nil.
func (r *renderer) jsType(t reflect.Type) (string, error) {
	if slices.Contains(r.cfg.Opaque, t) {
		return "Record<string, unknown>", nil
	}
	switch {
	case t == timeType:
		return "string", nil
	case t == rawMessageType:
		return "unknown", nil
	case t.Kind() != reflect.Pointer && t.Kind() != reflect.Interface &&
		(t.Implements(marshalerType) || reflect.PointerTo(t).Implements(marshalerType)):
		return "unknown", nil
	}
	switch t.Kind() {
	case reflect.Bool:
		return "boolean", nil
	case reflect.String:
		if lits := r.sources.constants(t); len(lits) > 0 {
			return strings.Join(lits, "|"), nil
		}
		return "string", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		if lits := r.sources.constants(t); len(lits) > 0 {
			return strings.Join(lits, "|"), nil
		}
		return "number", nil
	case reflect.Interface:
		return "unknown", nil
	case reflect.Pointer:
		return r.jsType(t.Elem())
	case reflect.Slice, reflect.Array:
		if isBytes(t) {
			return "string", nil
		}
		elem, err := r.jsType(t.Elem())
		if err != nil {
			return "", err
		}
		if strings.Contains(elem, "|") {
			return "Array<" + elem + ">", nil
		}
		return elem + "[]", nil
	case reflect.Map:
		elem, err := r.jsType(t.Elem())
		if err != nil {
			return "", err
		}
		return "Record<string, " + elem + ">", nil
	case reflect.Struct:
		if t.Name() == "" {
			return r.inline(t)
		}
		return r.nestedName(t)
	default:
		return "", fmt.Errorf("%v (%s) cannot travel as JSON", t, t.Kind())
	}
}

// inline renders an anonymous struct as an object literal type.
func (r *renderer) inline(t reflect.Type) (string, error) {
	fields, err := r.fields(t)
	if err != nil {
		return "", err
	}
	parts := make([]string, len(fields))
	for i, f := range fields {
		sep := ": "
		if f.optional {
			sep = "?: "
		}
		parts[i] = f.name + sep + f.jsType
	}
	return "{" + strings.Join(parts, ", ") + "}", nil
}

// nestedName is the typedef name a named struct is declared under, queuing
// its typedef the first time it is reached.
func (r *renderer) nestedName(t reflect.Type) (string, error) {
	if name, ok := r.nested[t]; ok {
		return name, nil
	}
	name := r.cfg.Rename[t]
	if name == "" {
		name = jsName(t.Name())
	}
	if owner, taken := r.names[name]; taken && owner != t {
		return "", fmt.Errorf("two typedefs are named %s (%v); give one a Config.Rename", name, t)
	}
	r.names[name] = t
	r.nested[t] = name
	r.queue = append(r.queue, t)
	return name, nil
}

// jsName is a Go type name as a typedef name: exported, so an unexported
// struct reads as a type in JS too.
func jsName(goName string) string {
	if goName == "" {
		return goName
	}
	return strings.ToUpper(goName[:1]) + goName[1:]
}

// literalUnion renders string literals as a JSDoc union of literal types.
func literalUnion(values []string) string {
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = jsString(v)
	}
	return strings.Join(parts, "|")
}

// jsString is a single-quoted JS string literal.
func jsString(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s) + "'"
}

func isBytes(t reflect.Type) bool {
	return t.Kind() == reflect.Slice && t.Elem().Kind() == reflect.Uint8 && t != rawMessageType
}
